import numpy as np

REPO = Path(__file__).resolve().parents[1]
R1 = REPO / "reports/r1"
QQ = "??"


def load(rel: str):
    p = R1 / rel
    return json.load(open(p)) if p.exists() else None


def f(x, d=3):
    return QQ if x is None or x != x else f"${x:.{d}f}$"


def pct(x, d=1):
    return QQ if x is None or x != x else f"${100 * x:.{d}f}$"


def pp(x, d=2):
    if x is None or x != x:
        return QQ
    v = 100 * x
    return f"${'-' if v < 0 else ''}{abs(v):.{d}f}$" if round(v, d) != 0 else f"${0:.{d}f}$"


TASK_NAMES = {"any": "any class"}


def charged(r):
    """Share of skipped detector work that came from target-bearing tiles (gross of gate cost)."""
    drop, skip = r["p_plus"] * (1 - r["tpr"]), (1 - r["p_plus"]) * (1 - r["fpr"])
    return drop / (drop + skip) if drop + skip > 0 else 0.0


