    rows = []
    for kind, name in (("full", "Full pass"), ("decoupled", "Decoupled gate"), ("fused", "Fused head")):
        cells = [name]
        acc = r["runs"][f"batched/{kind}"]["accept_rate"]
        cells.append(f(acc))
