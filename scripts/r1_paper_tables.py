        body.append(" & ".join([TASK_NAMES.get(d["task"], d["task"]), pct(r["p_plus"]), f(pr), f(d["full_pass"]["mAP50_coco"]),
                                pct(r["saving"]), pp(r["delta_mAP50_coco"]), f(r["tpr"]), f(r["fpr"]),
                                pct(charged(r), 0), pct(s["saving"]), pp(s["delta_mAP50_coco"])]) + r" \\")
