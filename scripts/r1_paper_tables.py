def fusing_table() -> str:
    """Fused OAN head against the decoupled gate. Seeds: mean and standard deviation over
    reports/r1/cascade/{fused,indep}/ship*.json when the repeats exist, else seed 67."""
    def runs(kind):
        out = []
        for name in ("ship", "ship_seed1", "ship_seed2"):
            d = load(f"cascade/{kind}/{name}.json")
            if d:
                out.append(d)
        return out
    rt = load("speed/runtime.json")
    cols = {k: runs(k) for k in ("fused", "indep")}
    def cell(kind, fn, fmt):
        vals = [fn(d) for d in cols[kind]]
        if not vals:
            return QQ
        if len(vals) == 1:
            return fmt(vals[0])
        m, s = float(np.mean(vals)), float(np.std(vals, ddof=1))
        return fmt(m)[:-1] + r" \pm " + fmt(s)[1:]
    P = lambda x: f"${100 * x:.1f}$"
    rows = [("Gate PR-AUC", lambda d: d["selections"]["risk"]["all"]["select_fold_prauc"], lambda x: f"${x:.3f}$"),
            ("Full-pass AP$@0.5$", lambda d: d["full_pass"]["mAP50_coco"], lambda x: f"${x:.3f}$"),
            ("Cascade $\\Delta$AP (pp)", lambda d: d["risk"]["pooled"]["delta_mAP50_coco"], lambda x: f"${100 * x:.2f}$"),
            ("Accept rate", lambda d: d["risk"]["pooled"]["accept_rate"], lambda x: f"${x:.3f}$"),
            ("Gate recall (TPR)", lambda d: d["risk"]["pooled"]["tpr"], lambda x: f"${x:.3f}$"),
            ("Saved, gate costed at zero (\\%)", lambda d: d["risk"]["pooled"]["saving_if_gate_free"], P),
            ("Saved, full accounting (\\%)", lambda d: d["risk"]["pooled"]["saving"], P)]
    body = [f"{name} & {cell('fused', fn, fmt)} & {cell('indep', fn, fmt)} \\\\" for name, fn, fmt in rows]
    if rt:
        for mode, lab in (("streaming", "Time saved, streaming (\\%)"), ("batched", "Time saved, batched (\\%)")):
            body.append(f"{lab} & {pct(rt['runs'][mode + '/fused']['time_saved_vs_full'])} & "
                        f"{pct(rt['runs'][mode + '/decoupled']['time_saved_vs_full'])} \\\\")
    n = len(cols["fused"])
    seeds = f"mean $\\pm$ standard deviation over {n} seeds" if n > 1 else "seed $67$; repeats pending"
    return r"""
\begin{table}[!t]
\centering
\caption{Fused against decoupled gating on DOTA-1.5 ships, both arms with a detector trained for $50$ epochs at patience $50$ (""" + seeds + r"""). Savings are of detector arithmetic at the operating points chosen on held-out scenes; the full accounting charges the fused head for the backbone prefix it reads and the decoupled gate for its own cost. Times are end to end (Table~\ref{tab:runtime}), measured on one seed at the thresholds chosen on all of DOTA validation, which accept slightly different shares of tiles.}
\label{tab:fusing}
\footnotesize
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lrr}
\toprule
 & Fused OAN head & Decoupled gate \\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{table}
"""


