        t = h["transfer"]["risk"]
        body.append(r"\midrule")
        body.append(" & ".join(["HRSC2016 (transfer)", pct(h["transfer"]["full_pass"]["p_plus"]), "---",
                                f(h["transfer"]["full_pass"]["mAP50_coco"]), pct(t["saving"]), pp(t["delta_mAP50_coco"]),
                                f(t["tpr"]), f(t["fpr"]), pct(charged(t), 0), "---", "---"]) + r" \\")
