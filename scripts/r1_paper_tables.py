def prauc_of(rel):
    """PR-AUC of a gate score file against the ships tile labels (all validation tiles)."""
    from sklearn.metrics import average_precision_score
    path = REPO / rel
    if not path.exists():
        return None
    s, y = [], []
    for line in open(path):
        r = json.loads(line)
        s.append(float(r["prob"]))
        y.append(int(r["label"]))
    return float(average_precision_score(y, s))


