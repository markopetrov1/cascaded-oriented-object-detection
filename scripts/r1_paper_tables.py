def main() -> int:
    """One file per table, so the manuscript can place each next to its first citation
    and the tables are numbered in the order the text cites them."""
    head = "% Generated by scripts/r1_paper_tables.py -- do not edit by hand.\n"
    out = {"sweep": sweep_table, "speed": speed_table, "runtime": runtime_table, "objects": objects_table,
           "fusing": fusing_table, "ece": ece_table, "strata": strata_table, "detsize": detsize_table,
           "codesign": codesign_table}
    for name, fn in out.items():
        (REPO / "paper").mkdir(exist_ok=True)
        (REPO / f"paper/generated_table_{name}.tex").write_text(head + fn().replace(head, ""))
    print("wrote", ", ".join(f"paper/generated_table_{n}.tex" for n in out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
